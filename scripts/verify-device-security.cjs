const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const root = path.join(__dirname, '..')
const security = fs.readFileSync(path.join(root, 'src', 'main', 'device-security.ts'), 'utf8')
const main = fs.readFileSync(path.join(root, 'src', 'main', 'index.ts'), 'utf8')
const preload = fs.readFileSync(path.join(root, 'src', 'preload', 'index.ts'), 'utf8')
const html = fs.readFileSync(path.join(root, 'src', 'renderer', 'index.html'), 'utf8')
const float = fs.readFileSync(path.join(root, 'src', 'renderer', 'float.js'), 'utf8')
const floatHtml = fs.readFileSync(path.join(root, 'src', 'renderer', 'float.html'), 'utf8')

assert.match(security, /id: 'password' \| 'antivirus' \| 'signatures' \| 'firewall'/)
assert.match(security, /NetUserGetInfo/)
assert.match(security, /SecurityCenter\.WscProductList/)
assert.match(security, /Get-MpComputerStatus/)
assert.match(security, /HNetCfg\.FwPolicy2/)
assert.match(security, /Get-NetFirewallProfile -PolicyStore ActiveStore/)
assert.match(security, /System\.Net\.NetworkInformation\.NetworkInterface/)
assert.match(security, /ConnectAsync\('1\.1\.1\.1', 443\)/)
assert.match(security, /checks\.filter\(\(check\) => check\.state === 'warning'\)\.length/)
assert.match(security, /checks\.filter\(\(check\) => check\.state === 'unknown'\)\.length/)
assert.match(security, /issueCount > 2 \? 'danger' : 'warning'/)
assert.doesNotMatch(security, /Set-MpPreference|Set-NetFirewallProfile|Set-ExecutionPolicy\s+(?!Bypass)/)
assert.match(main, /SECURITY_REFRESH_INTERVAL = 30 \* 60 \* 1000/)
assert.match(main, /STATUS_FLOAT_DEFAULT_WIDTH = 204/)
assert.match(main, /statusFloatWindow\.setAspectRatio\(STATUS_FLOAT_ASPECT_RATIO\)/)
assert.match(main, /async function resetToDefaults\(\)/)
assert.match(main, /ipcMain\.handle\('security:refresh', refreshSecurityReport\)/)
assert.match(main, /ipcMain\.handle\('app:reset', resetToDefaults\)/)
assert.match(preload, /resetToDefaults/)
assert.match(html, /设备安全态势/)
assert.match(html, /id="refresh-security"/)
assert.match(html, /id="reset-to-defaults"/)
assert.match(floatHtml, /登录用户/)
assert.match(floatHtml, /所属租户/)
assert.match(floatHtml, /租户网域/)
assert.match(floatHtml, /IP 地址/)
assert.match(floatHtml, /安全认证/)
assert.match(float, /个人用户/)
assert.match(float, /DevHjz/)
assert.match(float, /检测异常/)

console.log('Device security posture verification passed.')
