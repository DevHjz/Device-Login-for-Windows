const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const root = path.join(__dirname, '..')
const security = fs.readFileSync(path.join(root, 'src', 'main', 'device-security.ts'), 'utf8')
const main = fs.readFileSync(path.join(root, 'src', 'main', 'index.ts'), 'utf8')
const html = fs.readFileSync(path.join(root, 'src', 'renderer', 'index.html'), 'utf8')
const float = fs.readFileSync(path.join(root, 'src', 'renderer', 'float.js'), 'utf8')
const floatHtml = fs.readFileSync(path.join(root, 'src', 'renderer', 'float.html'), 'utf8')

assert.match(security, /id: 'password' \| 'antivirus' \| 'signatures' \| 'firewall'/)
assert.match(security, /Get-CimInstance -Namespace root\/SecurityCenter2 -ClassName AntivirusProduct/)
assert.match(security, /Get-MpComputerStatus/)
assert.match(security, /Get-NetFirewallProfile/)
assert.match(security, /Get-NetIPAddress -AddressFamily IPv4/)
assert.match(security, /Test-NetConnection -ComputerName '1\.1\.1\.1' -Port 443/)
assert.match(security, /issueCount === 0 \? 'pass' : issueCount <= 2 \? 'warning' : 'danger'/)
assert.doesNotMatch(security, /Set-MpPreference|Set-NetFirewallProfile|Set-ExecutionPolicy\s+(?!Bypass)/)
assert.match(main, /SECURITY_REFRESH_INTERVAL = 30 \* 60 \* 1000/)
assert.match(main, /void refreshSecurityReport\(\)/)
assert.match(main, /ipcMain\.handle\('security:refresh', refreshSecurityReport\)/)
assert.match(html, /设备安全态势/)
assert.match(html, /id="refresh-security"/)
assert.match(floatHtml, /登录用户/)
assert.match(floatHtml, /所属租户/)
assert.match(floatHtml, /租户网域/)
assert.match(floatHtml, /IP 地址/)
assert.match(floatHtml, /安全认证/)
assert.match(float, /个人用户/)
assert.match(float, /DevHjz/)

console.log('Device security posture verification passed.')
